'use strict';
const assert=require('node:assert/strict');
const core=require('../app-core.js'),seat=require('../seating-data.js');
const pupil=(name,cls,total,physics,math)=>({name,class:cls,subjects:{总分:{score:total,gradeRank:1000},物理:{score:physics},数学:{score:math}}});
const data=[pupil('甲','801',100,100,0),pupil('乙','01班',80,0,100),pupil('丙','一班',60,50,50),pupil('丁','701',40,'缺考',25),pupil('甲','802',999,999,999)];
const profiles=seat.buildProfiles(data,[],'01班','总分',[],[]);
assert.equal(profiles.length,4);assert.equal(profiles[0].totalPopulation,4);assert.equal(profiles[0].totalPercentile,0);
assert.equal(profiles.find(p=>p.name==='丁').totalPercentile,100);
assert.equal(profiles.find(p=>p.name==='乙').subjects.物理.score,0);
assert.equal(profiles.find(p=>p.name==='丁').subjects.物理.rank,null);
assert.ok(!profiles.find(p=>p.name==='丁').weaks.includes('物理'));
const state=seat.reconcile(profiles,null),a=state.students.find(s=>s.name==='甲'),b=state.students.find(s=>s.name==='乙'),d=state.students.find(s=>s.name==='丁');
